// Package domain defines the core types for the modeloff application.
package domain

import (
	"crypto/rand"
	"encoding/hex"
	"encoding/json"
	"fmt"
	"strings"
	"sync"
	"time"

	orderedmap "github.com/wk8/go-ordered-map/v2"
)

// InstanceID is a stable per-session identifier for an actor on the
// server. The human user's instance has an empty InstanceID; every
// model instance is assigned a unique one via GenerateInstanceID.
//
// InstanceID is the serialised wire form of identity (store columns,
// event-log records). Within the process the canonical handle is
// `*Instance`; callers compare instances by pointer identity.
type InstanceID string

// GenerateInstanceID returns a random 8-byte hex string suitable for
// use as a stable instance identifier.
func GenerateInstanceID() InstanceID {
	var b [8]byte
	_, _ = rand.Read(b[:])

	return InstanceID(hex.EncodeToString(b[:]))
}

// PersonaOrigin distinguishes how a persona was created.
type PersonaOrigin string

const (
	// PersonaGenerated marks a persona that was generated by the small model.
	PersonaGenerated PersonaOrigin = "generated"

	// PersonaUser marks a persona that was defined by the user.
	PersonaUser PersonaOrigin = "user"
)

// Persona describes a character that can be assigned to a model instance.
type Persona struct {
	ID          string        `json:"id"`
	Description string        `json:"description"`
	Origin      PersonaOrigin `json:"origin"`
}

// Nick represents a user or model nickname in the system.
type Nick string

// ChannelPrefix is the prefix a bare channel name gains.
const ChannelPrefix = "#"

// ChannelPrefixes are the characters RFC 2812 §1.3 admits as the
// first character of a channel name. `#` is the ordinary
// network-wide channel; `&` is the server-local one, which on a
// server that is one process is every bit as real (see
// [StatusChannelName]).
const ChannelPrefixes = "#&"

// ChannelName represents a chat channel name, carrying one of
// [ChannelPrefixes].
type ChannelName string

// HasChannelPrefix reports whether name starts with one of
// [ChannelPrefixes].
func HasChannelPrefix(name ChannelName) bool {
	return name != "" && strings.ContainsRune(ChannelPrefixes, rune(name[0]))
}

// NormaliseChannelName gives a bare name the default `#` prefix. A
// name that already carries a channel prefix keeps the one it has.
// Case is left alone: the spelling a channel is created with is the
// spelling the server puts on the wire, and [KeyForChannel] is what
// makes two spellings meet.
func NormaliseChannelName(name ChannelName) ChannelName {
	if !HasChannelPrefix(name) {
		return ChannelName(ChannelPrefix + string(name))
	}

	return name
}

// ModelID represents an OpenRouter model identifier (e.g. "anthropic/claude-3-haiku").
type ModelID string

// ChannelKind distinguishes channels from direct messages.
type ChannelKind int

// ChannelKind values distinguish between multi-user channels and
// one-to-one direct message conversations.
const (
	// KindChannel is a named channel that multiple users and models
	// can join (prefixed with # in the UI).
	KindChannel ChannelKind = iota

	// KindDM is a private conversation between the user and a
	// single model instance.
	KindDM

	// KindStatus is the per-session "server window" channel that
	// holds connection events, autojoin progress, and dispatch
	// errors. There is exactly one of these and it cannot be parted.
	KindStatus
)

// StatusChannelName is the reserved name the chat-screen uses for
// its local server-window view. It uses an IRC-style local-channel
// prefix to make it visually distinct from regular channels and
// impossible to collide with a user-created name (`/join`
// normalises bare names to `#`-prefixed). The session itself does
// not own a window under this name — it is purely a chat-screen
// rendering target for server-emitted events ([Welcome],
// [Reconnected], [ModelUnavailableError], …).
const StatusChannelName ChannelName = "&modeloff"

// StatusServerName is the server identity emitted on the wire as
// the source of server-originated events (RPL_WELCOME and similar
// numerics, NOTICE-shaped messages). It is the canonical "who is
// the server speaking" string clients render alongside a server
// message.
const StatusServerName Nick = "modeloff"

// InferChannelKind derives a channel's kind from its name alone. It
// is the single source of truth for callers that need to look up a
// channel in a sorted set keyed by `(Kind, Name)` but only have the
// name to hand: the reserved status name is `KindStatus`, a name
// carrying one of [ChannelPrefixes] is `KindChannel`, and a bare name
// is `KindDM`, because a DM is addressed by its counterpart's
// `InstanceID`, which carries no prefix.
func InferChannelKind(name ChannelName) ChannelKind {
	switch {
	case name == StatusChannelName:
		return KindStatus
	case HasChannelPrefix(name):
		return KindChannel
	default:
		return KindDM
	}
}

// Instance represents an actor on the IRC server. Both the human
// user and model instances share this type. The human user has an
// empty ModelID.
//
// Instance is an opaque handle: callers hold a `*Instance`, compare
// instances by pointer identity, and observe mutable attributes
// (nick, persona, channels) via the getter methods. Mutable fields
// are guarded by an internal RWMutex so concurrent readers see a
// consistent snapshot; writes (rare: a rename, a persona update, a
// join) take the write lock.
//
// Instance must be constructed via NewUserInstance or
// NewModelInstance. Zero-value Instance is reserved for internal
// wire-format stubs (see MemberList.UnmarshalJSON); do not use it
// elsewhere.
type Instance struct {
	instanceID InstanceID // immutable, set at construction
	ModelID    ModelID    // immutable, set at construction

	mu      sync.RWMutex
	nick    Nick
	persona string

	// channels is keyed by ChannelKey, so asking about a channel
	// answers the same however the asker spells it. The value keeps
	// the spelling the channel goes by, which is what every caller
	// reading the set back out needs; folding it away would make the
	// instance the one place in the session that cannot say what a
	// channel is called.
	channels *orderedmap.OrderedMap[ChannelKey, channelMembership]
}

// channelMembership is what an instance records about one channel it
// is in.
type channelMembership struct {
	name     ChannelName
	joinedAt time.Time
}

// NewUserInstance constructs the human user's Instance. The user
// carries the empty InstanceID as its stable identity marker and no
// ModelID. The channels map is initialised empty.
func NewUserInstance(nick Nick) *Instance {
	return newInstance("", "", nick, "", orderedmap.New[ChannelName, time.Time]())
}

// NewModelInstance constructs a model-backed Instance with the given
// identity, nick, model id, persona, and channels. If channels is
// nil, an empty ordered map is created.
//
// The caller must pass a non-empty InstanceID (use
// GenerateInstanceID). Empty IDs are reserved for the user sentinel
// constructed via NewUserInstance.
func NewModelInstance(id InstanceID, nick Nick, modelID ModelID, persona string, channels *orderedmap.OrderedMap[ChannelName, time.Time]) *Instance {
	if channels == nil {
		channels = orderedmap.New[ChannelName, time.Time]()
	}

	return newInstance(id, modelID, nick, persona, channels)
}

func newInstance(id InstanceID, modelID ModelID, nick Nick, persona string, channels *orderedmap.OrderedMap[ChannelName, time.Time]) *Instance {
	return &Instance{
		instanceID: id,
		ModelID:    modelID,
		nick:       nick,
		persona:    persona,
		channels:   keyedChannels(channels),
	}
}

// ID returns the stable InstanceID. This is the serialisation form
// of identity; within the process, callers should prefer pointer
// identity. Used by the store, event-log, and observability layers.
// Returns the empty InstanceID on a nil receiver, matching the
// zero-value shape of Nick/Persona/Channels.
func (i *Instance) ID() InstanceID {
	if i == nil {
		return ""
	}

	return i.instanceID
}

// Nick returns the instance's current display nick. The nick is
// mutable (via SetNick) so multiple calls may return different
// values after a rename.
func (i *Instance) Nick() Nick {
	if i == nil {
		return ""
	}

	i.mu.RLock()
	defer i.mu.RUnlock()

	return i.nick
}

// SetNick updates the display nick under the write lock. Backend-
// only; the frontend observes renames through `NickChangeEvent`
// rather than by mutating the handle directly.
func (i *Instance) SetNick(nick Nick) {
	i.mu.Lock()
	defer i.mu.Unlock()

	i.nick = nick
}

// Persona returns the current persona description.
func (i *Instance) Persona() string {
	if i == nil {
		return ""
	}

	i.mu.RLock()
	defer i.mu.RUnlock()

	return i.persona
}

// SetPersona updates the persona description under the write lock.
func (i *Instance) SetPersona(persona string) {
	i.mu.Lock()
	defer i.mu.Unlock()

	i.persona = persona
}

// Channels returns a snapshot of the instance's channels and the
// time it joined each, in join order, under the spelling each
// channel goes by. The returned map is a copy, so callers may read
// or iterate it without coordinating with writers; changing it
// changes nothing. Membership changes go through [Instance.JoinChannel]
// and [Instance.LeaveChannels].
func (i *Instance) Channels() *orderedmap.OrderedMap[ChannelName, time.Time] {
	if i == nil {
		return nil
	}

	i.mu.RLock()
	defer i.mu.RUnlock()

	return namedChannels(i.channels)
}

// InChannel reports whether the instance is currently in `ch`, under
// the server's casemapping, so the answer does not depend on how the
// asker spelled it. It answers directly under the read lock, where
// [Instance.Channels] would have to copy the whole ordered map
// first. The event-delivery filter asks this once per subscriber per
// event, so the copy is worth avoiding.
func (i *Instance) InChannel(ch ChannelName) bool {
	if i == nil {
		return false
	}

	i.mu.RLock()
	defer i.mu.RUnlock()

	if i.channels == nil {
		return false
	}

	_, ok := i.channels.Get(KeyForChannel(ch))

	return ok
}

// JoinChannel records that the instance is in `ch` as of `at`. A
// channel it is already in keeps the join time and the spelling it
// was first recorded under, which is what makes a repeat JOIN
// harmless.
func (i *Instance) JoinChannel(ch ChannelName, at time.Time) {
	i.mu.Lock()
	defer i.mu.Unlock()

	if i.channels == nil {
		i.channels = orderedmap.New[ChannelKey, channelMembership]()
	}

	key := KeyForChannel(ch)
	if _, ok := i.channels.Get(key); ok {
		return
	}

	i.channels.Set(key, channelMembership{name: ch, joinedAt: at})
}

// LeaveChannels drops each named channel from the instance's set.
// Naming a channel it is not in does nothing. Passing none leaves
// the set alone; [Instance.LeaveAllChannels] is how a caller clears
// it.
func (i *Instance) LeaveChannels(channels ...ChannelName) {
	i.mu.Lock()
	defer i.mu.Unlock()

	if i.channels == nil {
		return
	}

	for _, ch := range channels {
		i.channels.Delete(KeyForChannel(ch))
	}
}

// LeaveAllChannels empties the instance's channel set, for a caller
// that is taking the client off every channel at once.
func (i *Instance) LeaveAllChannels() {
	i.mu.Lock()
	defer i.mu.Unlock()

	i.channels = orderedmap.New[ChannelKey, channelMembership]()
}

// namedChannels projects the keyed membership map back to the
// channel-name form callers read, preserving join order.
func namedChannels(src *orderedmap.OrderedMap[ChannelKey, channelMembership]) *orderedmap.OrderedMap[ChannelName, time.Time] {
	out := orderedmap.New[ChannelName, time.Time]()

	if src == nil {
		return out
	}

	for pair := src.Oldest(); pair != nil; pair = pair.Next() {
		out.Set(pair.Value.name, pair.Value.joinedAt)
	}

	return out
}

// keyedChannels is namedChannels' inverse, for the two boundaries
// that hand over a name-keyed map: the constructors and JSON.
func keyedChannels(src *orderedmap.OrderedMap[ChannelName, time.Time]) *orderedmap.OrderedMap[ChannelKey, channelMembership] {
	out := orderedmap.New[ChannelKey, channelMembership]()

	if src == nil {
		return out
	}

	for pair := src.Oldest(); pair != nil; pair = pair.Next() {
		out.Set(KeyForChannel(pair.Key), channelMembership{name: pair.Key, joinedAt: pair.Value})
	}

	return out
}

// IsModel reports whether the instance is a model (as opposed to
// the human user).
func (i *Instance) IsModel() bool { return i.ModelID != "" }

// instanceJSON is the wire format for `Instance`. It mirrors the
// pre-handle struct so the store-column and existing test fixtures
// continue to deserialise unchanged.
type instanceJSON struct {
	InstanceID InstanceID                                     `json:"InstanceID"`
	Nick       Nick                                           `json:"Nick"`
	ModelID    ModelID                                        `json:"ModelID"`
	Persona    string                                         `json:"Persona"`
	Channels   *orderedmap.OrderedMap[ChannelName, time.Time] `json:"Channels"`
}

// MarshalJSON implements json.Marshaler. The read-lock is held for
// the duration of the snapshot build so concurrent mutations do not
// produce a torn record.
func (i *Instance) MarshalJSON() ([]byte, error) {
	if i == nil {
		return []byte("null"), nil
	}

	i.mu.RLock()
	snapshot := instanceJSON{
		InstanceID: i.instanceID,
		Nick:       i.nick,
		ModelID:    i.ModelID,
		Persona:    i.persona,
		Channels:   namedChannels(i.channels),
	}
	i.mu.RUnlock()

	return json.Marshal(snapshot)
}

// UnmarshalJSON implements json.Unmarshaler.
func (i *Instance) UnmarshalJSON(data []byte) error {
	if string(data) == "null" {
		return nil
	}

	var v instanceJSON
	if err := json.Unmarshal(data, &v); err != nil {
		return fmt.Errorf("unmarshal instance: %w", err)
	}

	i.mu.Lock()
	i.instanceID = v.InstanceID
	i.ModelID = v.ModelID
	i.nick = v.Nick
	i.persona = v.Persona
	i.channels = keyedChannels(v.Channels)
	i.mu.Unlock()

	return nil
}
